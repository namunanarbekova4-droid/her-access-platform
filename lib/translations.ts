export type UiKey = keyof typeof ui.en;

export function t(lang: string, key: UiKey): string {
  const locale = (lang in ui ? lang : "en") as Lang;
  return ui[locale][key];
}

export function getLocalizedGreeting(lang: string, name?: string): string {
  const hour = new Date().getHours();
  const key: UiKey = hour < 12 ? "goodMorning" : hour < 17 ? "goodAfternoon" : "goodEvening";
  const greeting = t(lang, key);
  return name ? `${greeting}, ${name}` : greeting;
}
